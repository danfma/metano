// Orchestrator of the transpile-conformance set (see ../README.md). Run through
// scripts/run-conformance.sh, which builds and transpiles the probes first. Runs under Bun.
//
// For every row (a public static string method of a *Probes class) it compares the current
// Bun and Node output with the .NET output and with the recorded Bun/Node output:
//   MATCH      the runtime prints what .NET prints
//   KNOWN GAP  it differs from .NET exactly as recorded (known-gaps.txt names the issue)
//   CHANGED    it differs from the recording (the regression signal; exit code 1)
//
// The recorded .NET output is the list of rows: a probe method the JavaScript side exposes but .NET
// does not (a private helper, or one with optional parameters) is not a row. The recording also
// carries a hash of the C# sources; when they changed the run fails until --record-dotnet.
import { createHash } from "node:crypto";
import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const toolsDir = dirname(fileURLToPath(import.meta.url));
const root = join(toolsDir, "..");
const work = join(root, ".work");
const recordedDir = join(root, "recorded");
const timeoutMs = Number(process.env.CONFORMANCE_TIMEOUT_MS ?? 30000);
const recordedCache = new Map();
const concurrency = 8;
const runtimes = ["bun", "node"];

const options = parseArguments(process.argv.slice(2));
const dotnetRows = options.liveDotnet || options.recordDotnet ? await runDotnet() : readRows("dotnet");
const modules = findModules();
const preloads = readPreloads();
const rowsToCheck = filterRows(dotnetRows);
const current = Object.fromEntries(
  await Promise.all(runtimes.map(async (runtime) => [runtime, await runRuntime(runtime)])),
);

if (options.recordDotnet) {
  writeRows("dotnet", dotnetRows, [...header("dotnet", "the .NET 10 output of every row"), `# sources-sha256: ${sourcesHash()}`]);
}

if (!options.recordDotnet && !options.liveDotnet && recordedSourcesHash() !== sourcesHash()) {
  console.error("conformance: FAILED, the probe C# sources changed since the .NET output was recorded; run scripts/run-conformance.sh --record-dotnet (or --record)");
  process.exit(1);
}

if (options.record) {
  for (const runtime of runtimes) {
    const divergences = new Map([...rowsToCheck].filter(([row, value]) => current[runtime].get(row) !== value));
    const lines = [...divergences.keys()].sort().map((row) => [row, current[runtime].get(row) ?? "MISSING"]);

    writeRows(runtime, new Map(lines), header(runtime, "only the rows that differ from .NET"));
  }
}

const gaps = readGaps();
const report = options.record ? [] : compare();

printReport(report);
process.exit(report.some((entry) => entry.failure) ? 1 : 0);

function parseArguments(args) {
  const parsed = { record: false, recordDotnet: false, liveDotnet: false, all: false, filter: null };

  for (let index = 0; index < args.length; index++) {
    const arg = args[index];

    if (arg === "--record") {
      parsed.record = true;
      parsed.recordDotnet = true;
    } else if (arg === "--record-dotnet") {
      parsed.recordDotnet = true;
    } else if (arg === "--live-dotnet") {
      parsed.liveDotnet = true;
    } else if (arg === "--all") {
      parsed.all = true;
    } else if (arg === "--filter") {
      parsed.filter = new RegExp(args[++index]);
    } else {
      console.error(`unknown option ${arg}`);
      process.exit(2);
    }
  }

  return parsed;
}

function sourcesHash() {
  const hash = createHash("sha256");
  const visit = (directory) => {
    for (const entry of readdirSync(directory).sort()) {
      const path = join(directory, entry);

      if (entry === ".work" || entry === "bin" || entry === "obj") {
        continue;
      }

      if (statSync(path).isDirectory()) {
        visit(path);
      } else if (/\.(cs|csproj)$/.test(entry)) {
        hash.update(`${relative(root, path)}\n`).update(readFileSync(path));
      }
    }
  };

  visit(root);

  return hash.digest("hex");
}

function recordedSourcesHash() {
  const file = join(recordedDir, "dotnet.txt");

  return existsSync(file) ? /^# sources-sha256: (\w+)$/m.exec(readFileSync(file, "utf8"))?.[1] : undefined;
}

function header(runtime, what) {
  return [
    `# Recorded ${runtime} output of the conformance probes: ${what}.`,
    "# Generated by scripts/run-conformance.sh --record; do not edit by hand.",
  ];
}

function readRows(name) {
  const file = join(recordedDir, `${name}.txt`);
  const rows = new Map();

  if (!existsSync(file)) {
    return rows;
  }

  for (const line of readFileSync(file, "utf8").split("\n")) {
    const match = /^(\w+\.\w+) (.*)$/.exec(line);

    if (match && !line.startsWith("#")) {
      rows.set(match[1], match[2]);
    }
  }

  return rows;
}

function writeRows(name, rows, headerLines) {
  mkdirSync(recordedDir, { recursive: true });

  const body = [...rows].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([row, value]) => `${row} ${value}`);

  writeFileSync(join(recordedDir, `${name}.txt`), `${[...headerLines, ...body].join("\n")}\n`);
}

function readGaps() {
  const file = join(root, "known-gaps.txt");
  const entries = [];

  if (!existsSync(file)) {
    return entries;
  }

  for (const line of readFileSync(file, "utf8").split("\n")) {
    const match = /^(\S+)\s+(#\d+|none)\b\s*(.*)$/.exec(line);

    if (match && !line.startsWith("#")) {
      const [, pattern, issue, note] = match;
      const prefix = pattern.endsWith(".*") ? pattern.slice(0, -1) : null;

      entries.push({ pattern, prefix, issue, note });
    }
  }

  return entries;
}

function gapFor(row) {
  return gaps.find((gap) => (gap.prefix ? row.startsWith(gap.prefix) : gap.pattern === row));
}

// tools/preloads.txt: `<module> <preload module>...`, module paths relative to the transpiled
// src/ without extension. The preloads are imported before the probe module, in order.
function readPreloads() {
  const file = join(toolsDir, "preloads.txt");
  const entries = new Map();

  if (!existsSync(file)) {
    return entries;
  }

  for (const line of readFileSync(file, "utf8").split("\n")) {
    const [module, ...preloadModules] = line.trim().split(/\s+/);

    if (module && !module.startsWith("#") && preloadModules.length > 0) {
      entries.set(module, preloadModules);
    }
  }

  return entries;
}

function filterRows(rows) {
  return options.filter ? new Map([...rows].filter(([row]) => options.filter.test(row))) : rows;
}

function findModules() {
  const found = [];
  const visit = (directory) => {
    for (const entry of readdirSync(directory)) {
      const path = join(directory, entry);

      if (statSync(path).isDirectory()) {
        visit(path);
      } else if (entry.endsWith("-probes.ts") && !entry.endsWith(".d.ts")) {
        found.push(relative(join(work, "probes", "src"), path).replace(/\.ts$/, ""));
      }
    }
  };

  visit(join(work, "probes", "src"));

  return found.sort();
}

function normalize(text) {
  return text.replaceAll(root, "<conformance>").replaceAll(/\r/g, "").trim();
}

function runProcess(command, args, cwd) {
  return new Promise((resolve) => {
    const child = spawn(command, args, { cwd, stdio: ["ignore", "pipe", "pipe"] });
    let stdout = "";
    let stderr = "";
    let timedOut = false;
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill("SIGKILL");
    }, timeoutMs);

    child.stdout.on("data", (chunk) => (stdout += chunk));
    child.stderr.on("data", (chunk) => (stderr += chunk));
    child.on("close", (code) => {
      clearTimeout(timer);
      resolve({ code, stdout, stderr, timedOut });
    });
  });
}

function parseRows(text) {
  const rows = new Map();

  for (const line of text.split("\n")) {
    const match = /^(\w+\.\w+) ((?:= |THROWS ).*)$/s.exec(line.replace(/\r$/, ""));

    if (match) {
      rows.set(match[1], match[2]);
    }
  }

  return rows;
}

async function runDotnet() {
  const project = join(root, "Conformance.csproj");
  const build = await runProcess("dotnet", ["build", project, "-v", "q", "-nologo", "-clp:ErrorsOnly"], root);

  if (build.code !== 0) {
    console.error(build.stdout + build.stderr);
    process.exit(2);
  }

  const run = await runProcess("dotnet", ["run", "--no-build", "--project", project], root);

  return parseRows(run.stdout);
}

async function runModule(runtime, module) {
  const isNode = runtime === "node";
  const base = join(work, "probes", isNode ? "dist" : "src");
  const fileOf = (name) => join(base, `${name}${isNode ? ".js" : ".ts"}`);
  const files = [fileOf(module), ...(preloads.get(module) ?? []).map(fileOf)];
  const args = isNode
    ? ["--import", join(toolsDir, "node-extensionless.mjs"), join(toolsDir, "run-probes.mjs"), ...files]
    : [join(toolsDir, "run-probes.mjs"), ...files];
  const result = await runProcess(runtime, args, work);
  const rows = parseRows(result.stdout);

  if (result.timedOut) {
    return { module, rows, failure: "TIMEOUT" };
  }

  if (result.code !== 0 || rows.size === 0) {
    const reason = normalize(result.stderr).split("\n").find((line) => /\w/.test(line) && !/^\s+at /.test(line));

    return { module, rows, failure: `LOADFAIL ${reason ?? `exit ${result.code}`}` };
  }

  return { module, rows, failure: null };
}

async function runRuntime(runtime) {
  const results = new Array(modules.length);
  let next = 0;
  const worker = async () => {
    while (next < modules.length) {
      const index = next++;

      results[index] = await runModule(runtime, modules[index]);
    }
  };

  await Promise.all(Array.from({ length: Math.min(concurrency, modules.length) }, worker));

  const merged = new Map();
  const squash = (text) => text.replaceAll("-", "").toLowerCase();

  for (const result of results) {
    for (const [row, value] of result.rows) {
      merged.set(row, value);
    }

    if (result.failure) {
      const moduleName = squash(result.module.split("/").at(-1));

      for (const row of dotnetRows.keys()) {
        if (!merged.has(row) && squash(row.split(".")[0]) === moduleName) {
          merged.set(row, result.failure);
        }
      }
    }
  }

  return merged;
}

function classify(runtime, row, expected) {
  const value = current[runtime].get(row) ?? "MISSING";
  const recordedDivergence = readRecorded(runtime).get(row);
  const recorded = recordedDivergence ?? expected;

  if (value === expected) {
    return { status: recordedDivergence === undefined ? "MATCH" : "MATCH*", value, recorded };
  }

  if (value === recorded) {
    const gap = gapFor(row);
    const label = gap ? (gap.issue === "none" ? "no issue" : gap.issue) : "unlisted";

    return { status: `KNOWN GAP (${label})`, value, recorded };
  }

  return { status: "CHANGED", value, recorded, failure: true };
}

function readRecorded(runtime) {
  if (!recordedCache.has(runtime)) {
    recordedCache.set(runtime, readRows(runtime));
  }

  return recordedCache.get(runtime);
}

function compare() {
  const entries = [];

  for (const [row, expected] of rowsToCheck) {
    const results = Object.fromEntries(runtimes.map((runtime) => [runtime, classify(runtime, row, expected)]));

    entries.push({ row, expected, results, failure: runtimes.some((runtime) => results[runtime].failure) });
  }

  return entries;
}

function describe(entry) {
  return runtimes
    .filter((runtime) => entry.results[runtime])
    .map((runtime) => `${runtime}: ${entry.results[runtime].status}`)
    .join(" | ");
}

function printReport(entries) {
  if (options.record) {
    console.log(`recorded ${rowsToCheck.size} rows (.NET, Bun, Node) into ${relative(process.cwd(), recordedDir) || "recorded"}/`);

    return;
  }

  const clean = (entry) => runtimes.every((runtime) => entry.results[runtime]?.status.startsWith("MATCH"));
  const interesting = entries.filter((entry) => options.all || !clean(entry));

  for (const entry of interesting) {
    console.log(`${entry.row.padEnd(48)} ${describe(entry)}`);

    for (const runtime of runtimes) {
      const result = entry.results[runtime];

      if (result?.status === "CHANGED") {
        console.log(`    .NET     ${entry.expected}`);
        console.log(`    recorded ${result.recorded ?? "(none)"}`);
        console.log(`    ${runtime.padEnd(8)} ${result.value}`);
      }
    }
  }

  const resolved = entries.filter((entry) => runtimes.some((runtime) => entry.results[runtime]?.status === "MATCH*"));

  for (const runtime of runtimes) {
    const tally = {};

    for (const entry of entries) {
      const status = entry.results[runtime]?.status.replace(/ \(.*\)$/, "").replace("*", "");

      if (status) {
        tally[status] = (tally[status] ?? 0) + 1;
      }
    }

    const parts = Object.entries(tally).map(([status, count]) => `${count} ${status}`);

    console.log(`${runtime.padEnd(5)} ${entries.length} rows: ${parts.join(", ")}`);
  }

  if (resolved.length > 0) {
    console.log(
      `note: ${resolved.length} row(s) now match .NET where the recording diverged (re-run with --record, and drop them from known-gaps.txt): ${resolved.map((entry) => entry.row).join(", ")}`,
    );
  }

  const failed = entries.filter((entry) => entry.failure);

  console.log(failed.length === 0 ? "conformance: OK (no row CHANGED)" : `conformance: FAILED (${failed.length} row(s) CHANGED)`);
}
