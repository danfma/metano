using Microsoft.CodeAnalysis;

namespace Metano.Compiler.Frontend.Roslyn;

/// <summary>
/// Tells source-generator output (for example the System.Text.Json <c>*.g.cs</c>
/// files) apart from user-authored code, so validations that police what the user
/// wrote — such as <c>MS0013</c> — skip code nobody authored by hand.
/// <para>
/// When the workspace reports its generated documents
/// (<c>Project.GetSourceGeneratedDocumentsAsync</c>, or a generator driver's
/// <c>GeneratedTrees</c>), that list is authoritative and matched by file path: a
/// user file that merely looks generated is still user code. Only a
/// <see cref="Compilation"/> built in memory without such a list falls back to the
/// conventions — a <c>.g.cs</c> path or a leading <c>&lt;auto-generated&gt;</c>
/// comment.
/// </para>
/// </summary>
internal sealed class GeneratedSourceTrees
{
    private const string GeneratedFileSuffix = ".g.cs";

    // Left unclosed on purpose: generators write both `<auto-generated/>` and
    // `<auto-generated>` (with a closing tag further down the header).
    private const string AutoGeneratedMarker = "<auto-generated";

    private readonly IReadOnlySet<string>? _reportedFilePaths;

    private GeneratedSourceTrees(IReadOnlySet<string>? reportedFilePaths)
    {
        _reportedFilePaths = reportedFilePaths;
    }

    /// <summary>
    /// Generated trees as the workspace reported them; nothing else counts as generated.
    /// </summary>
    public static GeneratedSourceTrees Reported(IEnumerable<string> generatedFilePaths) =>
        new(generatedFilePaths.Where(path => path.Length > 0).ToHashSet(StringComparer.Ordinal));

    /// <summary>
    /// No workspace list available: recognize generated trees by convention.
    /// </summary>
    public static GeneratedSourceTrees ByConvention() => new(reportedFilePaths: null);

    public bool Contains(SyntaxTree tree) =>
        _reportedFilePaths is null
            ? LooksGenerated(tree)
            : _reportedFilePaths.Contains(tree.FilePath);

    /// <summary>
    /// <c>true</c> when the symbol has source declarations and every one of them
    /// lives in generated code — a member the generator added to a user's partial
    /// type, or a type the generator declared outright.
    /// </summary>
    public bool DeclaresOnlyGeneratedCode(ISymbol symbol) =>
        symbol.DeclaringSyntaxReferences.Length > 0
        && symbol.DeclaringSyntaxReferences.All(reference => Contains(reference.SyntaxTree));

    private static bool LooksGenerated(SyntaxTree tree) =>
        HasGeneratedFileSuffix(tree) || HasAutoGeneratedHeader(tree);

    private static bool HasGeneratedFileSuffix(SyntaxTree tree) =>
        tree.FilePath.EndsWith(GeneratedFileSuffix, StringComparison.OrdinalIgnoreCase);

    private static bool HasAutoGeneratedHeader(SyntaxTree tree) =>
        tree.GetRoot()
            .GetLeadingTrivia()
            .Any(trivia =>
                trivia.ToString().Contains(AutoGeneratedMarker, StringComparison.OrdinalIgnoreCase)
            );
}
