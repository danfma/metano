using Microsoft.CodeAnalysis;

namespace Metano.Compiler.Frontend.Roslyn;

/// <summary>
/// Tells source-generator output (for example the System.Text.Json <c>*.g.cs</c>
/// files) apart from user-authored code, so validations that police what the user
/// wrote — such as <c>MS0013</c> — skip code nobody authored by hand.
/// <para>
/// The authoritative set is the one the workspace reports
/// (<c>Project.GetSourceGeneratedDocumentsAsync</c>), matched by file path. Callers
/// that build a <see cref="Compilation"/> in memory (the test suite, other in-process
/// hosts) may not have that set, so a tree is also treated as generated when its path
/// ends in <c>.g.cs</c> or its leading comment carries the conventional
/// <c>&lt;auto-generated&gt;</c> marker.
/// </para>
/// </summary>
internal sealed class GeneratedSourceTrees
{
    private const string GeneratedFileSuffix = ".g.cs";
    private const string AutoGeneratedMarker = "<auto-generated";

    private readonly IReadOnlySet<string> _generatedFilePaths;

    public GeneratedSourceTrees(IEnumerable<string> generatedFilePaths)
    {
        _generatedFilePaths = generatedFilePaths
            .Where(path => path.Length > 0)
            .ToHashSet(StringComparer.Ordinal);
    }

    public bool Contains(SyntaxTree tree) =>
        _generatedFilePaths.Contains(tree.FilePath)
        || tree.FilePath.EndsWith(GeneratedFileSuffix, StringComparison.OrdinalIgnoreCase)
        || HasAutoGeneratedHeader(tree);

    /// <summary>
    /// <c>true</c> when the symbol has source declarations and every one of them
    /// lives in generated code — a member the generator added to a user's partial
    /// type, or a type the generator declared outright.
    /// </summary>
    public bool DeclaresOnlyGeneratedCode(ISymbol symbol) =>
        symbol.DeclaringSyntaxReferences.Length > 0
        && symbol.DeclaringSyntaxReferences.All(reference => Contains(reference.SyntaxTree));

    private static bool HasAutoGeneratedHeader(SyntaxTree tree) =>
        tree.GetRoot()
            .GetLeadingTrivia()
            .Any(trivia =>
                trivia.ToString().Contains(AutoGeneratedMarker, StringComparison.OrdinalIgnoreCase)
            );
}
